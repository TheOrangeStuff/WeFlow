"""Bake the app's own SmugMug / Flickr API keys into the build.

Reads WEFLOW_SMUGMUG_API_KEY, WEFLOW_SMUGMUG_API_SECRET, WEFLOW_FLICKR_API_KEY and
WEFLOW_FLICKR_API_SECRET from the environment and writes WeFlow/core/_builtin_keys.py
(git-ignored). With no keys set, the app asks each user for their own API key.
"""

from __future__ import annotations

import os
from pathlib import Path

NAMES = ("SMUGMUG_API_KEY", "SMUGMUG_API_SECRET", "FLICKR_API_KEY", "FLICKR_API_SECRET")
TARGET = Path(__file__).resolve().parent.parent / "WeFlow" / "core" / "_builtin_keys.py"


def main() -> None:
    lines = ['"""Generated by packaging/write_builtin_keys.py. Never commit."""', ""]
    found = 0
    for name in NAMES:
        value = os.environ.get(f"WEFLOW_{name}", "")
        found += bool(value)
        lines.append(f"{name} = {value!r}")
    TARGET.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {TARGET.name} with {found} of {len(NAMES)} keys set")


if __name__ == "__main__":
    main()
